bool epdDrawImageDiff(Rect_t area, const uint8_t* toPacked, const uint8_t* fromPacked,
                       const Ed047Tc1WaveformPhases& phases) {
  // area.x != 0 isn't handled (see the scope note in the header) -- row
  // extraction below reads from column 0, so a nonzero x would silently read
  // the wrong columns. Fail loudly instead; the caller falls back to the
  // legacy path.
  if (area.width <= 0 || area.height <= 0 || area.x != 0 || (area.width % 4) != 0) return false;
  if (!ensureLut()) return false;

  // Naturally 2-byte-aligned storage for the interlaced row (CLAUDE.md's
  // RISC-V alignment rule): calcDiffRow() reads this as uint16_t pairs, so it
  // must be a uint16_t array, not a uint8_t buffer reinterpret_cast to
  // uint16_t*. Written via a uint8_t* view below (byte writes need no
  // alignment) and read via the uint16_t view for the paired lookup.
  uint16_t interlacedRow16[EPD_WIDTH / 2];
  uint8_t* const interlacedRow = reinterpret_cast<uint8_t*>(interlacedRow16);

  constexpr int32_t kStrideBytes = EPD_WIDTH / 2;

  for (int frame = 0; frame < phases.phases; ++frame) {
    buildDiffLut(g_lut, phases, frame);
    epd_start_frame();
    for (int32_t row = 0; row < EPD_HEIGHT; ++row) {
      if (row < area.y || row >= area.y + area.height) {
        epd_skip();
        continue;
      }
      const uint8_t* toRow = toPacked + static_cast<size_t>(row) * kStrideBytes;
      const uint8_t* fromRow = fromPacked + static_cast<size_t>(row) * kStrideBytes;
      interlaceDiffRow(toRow, fromRow, area.width, interlacedRow);
      calcDiffRow(interlacedRow16, epd_get_current_buffer(), g_lut, area.width);
      epd_output_row(static_cast<uint32_t>(phases.phaseTimesDus[frame]));
    }
    epd_end_frame();
  }
  return true;
}

