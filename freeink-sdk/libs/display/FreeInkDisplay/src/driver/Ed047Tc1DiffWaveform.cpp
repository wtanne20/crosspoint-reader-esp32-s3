// 65536-byte (to,from)-pair -> 2-bit push code table, rebuilt once per phase.
// Internal DRAM (not PSRAM): read via random-access lookup from a hot loop,
// same MALLOC_CAP_8BIT-only placement as ed047tc1/epd_driver.c's own
// conversion_lut for the same reason.
uint8_t* g_lut = nullptr;

bool ensureLut() {
  if (g_lut) return true;
  g_lut = static_cast<uint8_t*>(heap_caps_malloc(1 << 16, MALLOC_CAP_8BIT));
  return g_lut != nullptr;
}

// Modeled on epdiy's build_1ppB_lut_64k (src/output_common/lut.c): builds a
// 256-entry base table indexed by an interlaced (to<<4)|from byte, each entry
// a 2-bit push code, then fans it out to 64K so two packed interlaced bytes
// (2 pixels) can be looked up in one 16-bit read -- see calcDiffRow().
void buildDiffLut(uint8_t* lut, const Ed047Tc1WaveformPhases& phases, int frame) {
  const uint8_t* p = phases.luts + (16 * 4 * frame);
  for (uint32_t to = 0; to < 16; ++to) {
    for (uint32_t fromGroup = 0; fromGroup < 4; ++fromGroup) {
      const uint32_t index = (to << 4) | (fromGroup * 4);
      const uint8_t packed = p[to * 4 + fromGroup];
      lut[index + 0] = (packed >> 6) & 0x3;
      lut[index + 1] = (packed >> 4) & 0x3;
      lut[index + 2] = (packed >> 2) & 0x3;
      lut[index + 3] = (packed >> 0) & 0x3;
    }
  }
  for (int32_t outer = 0xFF; outer >= 0; --outer) {
    uint32_t outerResult = static_cast<uint32_t>(lut[outer]) << 2;
    outerResult |= outerResult << 16;
    outerResult |= outerResult << 8;
    uint8_t* section = lut + (outer << 8);
    memcpy(section, lut, 0x100);
    // outer<<8 is always a multiple of 256, so `section` is always 4-byte
    // aligned here (and g_lut itself comes from heap_caps_malloc, which
    // guarantees at least 4-byte alignment) -- safe per CLAUDE.md's
    // RISC-V alignment rule.
    uint32_t* section32 = reinterpret_cast<uint32_t*>(section);
    for (int32_t i = 0; i < 0x100 / 4; ++i) {
      section32[i] |= outerResult;
    }
  }
}

// Packs one row's (to,from) 4-bit pixel-value pairs into `out` (width bytes,
// one per pixel: (to<<4)|from). toRow/fromRow are packed 4bpp (2px/byte, low
// nibble = even column, high nibble = odd column -- matches
// Ed047Tc1Driver.cpp's convertRect()).
void interlaceDiffRow(const uint8_t* toRow, const uint8_t* fromRow, int32_t width, uint8_t* out) {
  for (int32_t col = 0; col < width; ++col) {
    const uint8_t toByte = toRow[col >> 1];
    const uint8_t fromByte = fromRow[col >> 1];
    const uint8_t toNib = (col & 1) ? (toByte >> 4) : (toByte & 0x0F);
    const uint8_t fromNib = (col & 1) ? (fromByte >> 4) : (fromByte & 0x0F);
    out[col] = static_cast<uint8_t>((toNib << 4) | fromNib);
  }
}

// Modeled on epdiy's calc_epd_input_1ppB_64k (src/output_common/lut.c): looks
// up 2 packed interlaced bytes (4 pixels) at a time via a uint16_t read, and
// writes one output byte per 4 pixels -- the same density
// epd_driver.c's calc_epd_input_4bpp produces, so this is a drop-in source of
// epd_get_current_buffer() rows. `interlacedRow16` must be a uint16_t-typed
// array (not a uint8_t buffer reinterpreted in place) so this read is
// naturally aligned -- see epdDrawImageDiff().
void calcDiffRow(const uint16_t* interlacedRow16, uint8_t* epdOutput, const uint8_t* lut, int32_t width) {
  for (int32_t j = 0; j < width / 4; ++j) {
    epdOutput[j] = static_cast<uint8_t>((lut[interlacedRow16[2 * j + 1]] << 4) | lut[interlacedRow16[2 * j]]);
  }
}

